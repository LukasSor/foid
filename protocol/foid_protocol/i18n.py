TRANSLATIONS: dict[str, dict[str, str]] = {
    "en": _EN,
    "de": _DE,
}


def normalize_locale(value: Any) -> str:
    text = str(value or "").strip().lower()
    if text in TRANSLATIONS:
        return text
    return DEFAULT_LOCALE


def status_i18n_key(code: Any) -> str:
    text = str(code or "").strip().lower()
    if text == "ok":
        return "status.ok"
    if text == "connected":
        return "status.connected"
    if text == "offline":
        return "status.offline"
    if text in {"optional", "status.optional"}:
        return "status.optional"
    return "status.not_installed"


def t(locale: str | None, key: str, **kwargs: Any) -> str:
    bundle = TRANSLATIONS.get(normalize_locale(locale), _EN)
    template = bundle.get(key) or _EN.get(key) or key
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def bundle(locale: str | None = None) -> dict[str, str]:
    chosen = normalize_locale(locale)
    merged = dict(_EN)
    merged.update(TRANSLATIONS[chosen])
    return merged


def javascript_bundle() -> str:
    payload = {"en": _EN, "de": _DE, "default": DEFAULT_LOCALE}
    return "window.FOID_I18N = " + json.dumps(payload, ensure_ascii=False) + ";"
